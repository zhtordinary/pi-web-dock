import assert from "node:assert/strict";
import test from "node:test";
import { createRequire } from "node:module";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
const core = createRequire(import.meta.url)("../bin/session-wait-core.cjs");
test("source attribution never grants verification, and cancel leaves running tasks alone", t => {
  const root = mkdtempSync(join(tmpdir(), "wait-upgrade-")); t.after(() => rmSync(root, { recursive: true, force: true }));
  const owner = { deviceId: "d", sessionId: "owner" }, target = { deviceId: "d", sessionId: "target" };
  const wait = core.createWait(root, "reader", { owner, target, condition: "acceptance_passed" });
  core.applyEvent(root, "reader", { type: "acceptance_passed", waitId: wait.id, identity: target, success: true, acceptance: { criterion: "test", digest: "digest" }, evidenceSource: "user_confirmation" });
  const saved = Object.values(core.readState(root, "reader").events).find(event => event.type === "acceptance_passed");
  assert.equal(saved.evidenceSource, "user_confirmation");
  const pending = core.createWait(root, "reader", { owner, target, condition: "task_completed" });
  const task = core.enqueueExternalTask(root, "reader", { waitId: pending.id, resultLocation: join(root, "result"), argv: [process.execPath, "-e", ""] });
  core.updateExternalTask(root, "reader", task.id, { status: "running", pid: process.pid });
  core.transitionWait(root, "reader", pending.id, "cancel");
  assert.equal(core.listExternalTasks(root, "reader")[0].status, "running");
  const late = core.applyEvent(root, "reader", { type: "task_completed", waitId: pending.id, identity: target, success: true, resultLocation: "/fixture" });
  assert.equal(late.reason, "wait_cancelled"); assert.equal(core.getStatus(root, "reader", { waitId: pending.id }).waits.length, 0); assert.equal(core.readState(root, "reader").terminalWaits[pending.id].status, "cancelled");
});
