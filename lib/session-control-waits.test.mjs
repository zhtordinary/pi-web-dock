import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { createJiti } from "jiti";

test("session_control registers a durable wait and reports a structured result without a live target", async (t) => {
  const root = mkdtempSync(join(tmpdir(), "reader-session-control-waits-")); t.after(() => rmSync(root, { recursive: true, force: true }));
  const previous = process.env.PI_WEB_SESSION_WAIT_STATE_ROOT; process.env.PI_WEB_SESSION_WAIT_STATE_ROOT = root;
  t.after(() => { if (previous === undefined) delete process.env.PI_WEB_SESSION_WAIT_STATE_ROOT; else process.env.PI_WEB_SESSION_WAIT_STATE_ROOT = previous; });
  const jiti = createJiti(import.meta.url, { alias: { "@": process.cwd() }, interopDefault: true, moduleCache: false });
  const { createSessionControlExtension } = await jiti.import("./session-control.ts");
  let definition;
  createSessionControlExtension().factory({ registerTool(value) { definition = value; } });
  const sessionFile = join(root, "owner.jsonl");
  const session = { sessionId: "owner", sessionFile, cwd: "/fixture", inner: { sessionManager: { getSessionId: () => "owner", getSessionFile: () => sessionFile, getHeader: () => ({ id: "owner", cwd: "/fixture" }), getSessionName: () => "owner" } } };
  const run = async (id, params) => JSON.parse((await definition.execute(id, params, undefined, undefined, { cwd: "/fixture", sessionManager: session.inner.sessionManager })).content[0].text);
  const wait = await run("register", { action: "register_wait", target: "owner", condition: "task_completed", taskId: "task-1", continuation: { target: { deviceId: "fixture", sessionId: "owner" }, authorizedScope: ["resume_prior_work"], message: "Continue approved work" } });
  assert.equal(wait.status, "waiting");
  assert.equal(wait.registered, true);
  assert.equal(wait.readiness.driver, "reader");
  assert.equal(wait.readiness.status, "ready");
  const result = await run("report", { action: "report_result", waitId: wait.id, taskId: "task-1", event: { type: "task_completed", success: true, resultLocation: "/fixture/result.json" } });
  assert.equal(result.accepted, true); assert.equal(result.event.outcome, "completed");
  const status = await run("status", { action: "get_wait", waitId: wait.id });
  assert.equal(status.waits[0].status, "completed");
  assert.equal(status.waits[0].readiness.status, "inactive");
  assert.equal(status.waits[0].evidenceSource, "unspecified");
});
