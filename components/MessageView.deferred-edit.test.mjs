import assert from 'node:assert/strict';
import test from 'node:test';
import {readFile} from 'node:fs/promises';
import {createJiti} from 'jiti';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {markupText,testTranslator} from './test-locale.mjs';
const jiti=createJiti(import.meta.url,{jsx:{runtime:'automatic'},tsconfigPaths:true});
const {MessageView}=await jiti.import('./MessageView.tsx');
const {I18nProvider}=await jiti.import('../hooks/useI18n.tsx');
const {createHistoryProjection,getHistoryWindow,readHistoryContent}=await jiti.import('../lib/session-history.ts');
const {readHistoryEditMessage}=await jiti.import('../lib/history-edit-message.ts');
const {TranscriptReader}=await jiti.import('../lib/transcript-reader.ts');
test('a large user message is automatically restored before rendering and keeps its edit button and original images',async t=>{
  const original={role:'user',content:[{type:'text',text:'long question '.repeat(12_000)},{type:'image',data:'AQID',mimeType:'image/png'}]};
  const projection=createHistoryProjection([{type:'message',id:'u',parentId:null,timestamp:'2026-10-19T00:00:00Z',message:original}],{sessionId:'s'});
  const item=getHistoryWindow(projection).items[0];assert.ok(item.deferred.length>0);
  const source=await readFile(new URL('./ChatWindow.tsx',import.meta.url),'utf8');
  assert.match(source,/onEditContent=\{sessionBusy \|\| sideBranchPending \? undefined : handleEditContent\}/);
  const reader=new TranscriptReader({sessionId:'s'},async(_scope,request)=>request.mode==='window'?getHistoryWindow(projection,request):readHistoryContent(projection,request));
  t.after(()=>reader.dispose());
  assert.ok(await reader.reset(),JSON.stringify(reader.getState().error));
  const rendered=reader.getState().transcript.items.get(item.entryId);
  assert.deepEqual(rendered.deferred,[]);
  assert.equal(rendered.message.content[0].text,original.content[0].text);
  const html=renderToStaticMarkup(React.createElement(I18nProvider,{initialLocale:'en'},React.createElement(MessageView,{message:rendered.message,entryId:item.entryId,isFirstUserMessage:true,onEditContent:()=>{}})));
  assert.ok(html.includes(markupText(testTranslator('en')('message.pullBackEdit'))));
  const restored=await readHistoryEditMessage({...projection,entryId:'u'},async options=>readHistoryContent(projection,options),()=>true);
  assert.deepEqual(restored,original);
  assert.ok(getHistoryWindow(projection).items[0].deferred.length>0,'reading content does not have to mutate the cached bounded preview to unlock editing');
});
